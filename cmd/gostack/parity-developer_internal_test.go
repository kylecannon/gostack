const developerFilePrefix = "developer-"

// Test_developerFilesHoldNoRoutingHook holds the rule behind DEVELOPER_PREFIX
// in parity/ledger.py: a change to internal/service/<svc>/developer-*.go
// selects <svc> and its dependents, not every service, because nothing a
// routing hook runs is declared there. A hook runs code of the package, so the
// rule has two halves, both checked here for every registration:
//   - a function it sets as Mount, ClaimHost, Claim, Fallback or Preprocess is
//     not declared in a developer file;
//   - no file of the package outside developer-*.go (a test file apart) names
//     anything a developer file declares, and names the DeveloperMount
//     function only as the value of the DeveloperMount key in the Registration
//     literal. Developer files may use the rest of the package.
func Test_developerFilesHoldNoRoutingHook(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", ".."))
	require.NoError(t, err)

	regs := buildRegistrations(t)
	hooks, developers := 0, 0

	for i := range regs {
		reg := &regs[i]
		dir := filepath.Join(root, "internal", "service", reg.Metadata.Name)
		outside := decls(t, dir, false)
		// A name a file outside developer-*.go declares too, a method of
		// another type for one, cannot be told from the developer one by name.
		declared := slices.DeleteFunc(decls(t, dir, true), func(name string) bool { return slices.Contains(outside, name) })

		for hook, fn := range routingHooks(reg) {
			hooks++

			name, file := funcOf(fn)
			require.False(t, strings.HasPrefix(filepath.Base(file), developerFilePrefix),
				"%s.%s is %s, in %s: a developer file holds no routing hook", reg.Metadata.Name, hook, name, file)
			require.NotContains(t, declared, name,
				"%s.%s is %s, declared in a developer-*.go file: it holds no routing hook", reg.Metadata.Name, hook, name)
		}

		// A service with no developer file has nothing to keep apart. One with
		// such a file must mount it through DeveloperMount: the file selects
		// only the service and its dependents (parity/ledger.py), which is right
		// only for code the router scoped to the service's prefix runs.
		if len(declared) == 0 {
			continue
		}

		require.NotNil(t, reg.DeveloperMount,
			"%s has developer-*.go files and no DeveloperMount: they select only its suites", reg.Metadata.Name)

		developers++

		mountName, _ := funcOf(reg.DeveloperMount)

		require.Empty(t, outsideUses(t, dir, declared, mountName),
			"%s: files outside developer-*.go use what a developer file declares, "+
				"or name the DeveloperMount function outside the Registration literal", reg.Metadata.Name)
	}

	require.Positive(t, hooks, "no routing hook was checked")
	require.Positive(t, developers, "no developer file was checked")
}

// routingHooks returns the hooks reg sets, by field name.
func routingHooks(reg *service.Registration) map[string]any {
	hooks := map[string]any{}

	for name, fn := range map[string]any{
		"Mount": reg.Mount, "ClaimHost": reg.ClaimHost, "Claim": reg.Claim,
		"Fallback": reg.Fallback, "Preprocess": reg.Preprocess,
	} {
		if !reflect.ValueOf(fn).IsNil() {
			hooks[name] = fn
		}
	}

	return hooks
}

// funcOf returns the name the function of fn is declared as, without its
// package and receiver, and the file the runtime places it in. A method value
// is a compiler-made wrapper, "<autogenerated>" in file, whose name ends in
// "-fm"; its declaring file is found by name.
func funcOf(fn any) (name, file string) {
	pc := reflect.ValueOf(fn).Pointer()
	f := runtime.FuncForPC(pc)
	file, _ = f.FileLine(pc)
	name = f.Name()
	name = name[strings.LastIndex(name, ".")+1:]

	return strings.TrimSuffix(name, "-fm"), file
}

// decls lists the names declared at top level (constants, variables, types,
// functions and methods) in the developer-*.go files of the package in dir, or
// in its other non-test files.
func decls(t *testing.T, dir string, developer bool) []string {
	t.Helper()

	var names []string

	for _, path := range goFiles(t, dir, developer) {
		for _, decl := range parseGo(t, path).Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				names = append(names, decl.Name.Name)
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					names = append(names, specNames(spec)...)
				}
			default:
				// A bad declaration, which parsing already reported.
			}
		}
	}

	return slices.DeleteFunc(names, func(name string) bool { return name == "_" })
}

func specNames(spec ast.Spec) []string {
	switch spec := spec.(type) {
	case *ast.TypeSpec:
		return []string{spec.Name.Name}
	case *ast.ValueSpec:
		names := make([]string, 0, len(spec.Names))
		for _, name := range spec.Names {
			names = append(names, name.Name)
		}

		return names
	default:
		return nil
	}
}

// outsideUses lists each identifier of the non-test files of dir outside
// developer-*.go that is one of declared, or is mountName, the DeveloperMount
// function. mountName passes only as the value of the DeveloperMount key of a
// Registration literal: a call, a method value assigned elsewhere or a
// reference from Mount or MountProtocol code puts the developer routes where a
// routing hook runs, outside the prefix the gateway scopes them to. It matches
// by name, so a local variable or a field that shares a name is listed too;
// rename it. Each use reads "file:line: name".
func outsideUses(t *testing.T, dir string, declared []string, mountName string) []string {
	t.Helper()

	var uses []string

	for _, path := range goFiles(t, dir, false) {
		fset := token.NewFileSet()
		parsed, err := parser.ParseFile(fset, path, nil, 0)
		require.NoError(t, err)

		registered := registeredMounts(parsed)

		ast.Inspect(parsed, func(n ast.Node) bool {
			id, ok := n.(*ast.Ident)
			if !ok || registered[id] || (id.Name != mountName && !slices.Contains(declared, id.Name)) {
				return true
			}

			uses = append(uses, fmt.Sprintf("%s:%d: %s", filepath.Base(path), fset.Position(id.Pos()).Line, id.Name))

			return true
		})
	}

	return uses
}

// registeredMounts returns the identifiers that name the DeveloperMount
// function where a Registration literal sets it: the value of its
// DeveloperMount key, when that is a plain name or a selector such as
// p.mountDeveloperAPI. Anything else in the value, a wrapping function
// literal or a call, names it as code and is not returned.
func registeredMounts(file *ast.File) map[*ast.Ident]bool {
	registered := map[*ast.Ident]bool{}

	ast.Inspect(file, func(n ast.Node) bool {
		lit, ok := n.(*ast.CompositeLit)
		if !ok || !isRegistration(lit.Type) {
			return true
		}

		for _, elt := range lit.Elts {
			pair, ok := elt.(*ast.KeyValueExpr)
			if !ok {
				continue
			}

			if key, ok := pair.Key.(*ast.Ident); !ok || key.Name != "DeveloperMount" {
				continue
			}

			switch value := pair.Value.(type) {
			case *ast.Ident:
				registered[value] = true
			case *ast.SelectorExpr:
				registered[value.Sel] = true
			default:
				// Not a name: whatever it holds is listed as a use.
			}
		}

		return true
	})

	return registered
}

// isRegistration reports whether typ names service.Registration, or
// Registration inside package service.
func isRegistration(typ ast.Expr) bool {
	switch typ := typ.(type) {
	case *ast.Ident:
		return typ.Name == "Registration"
	case *ast.SelectorExpr:
		return typ.Sel.Name == "Registration"
	default:
		return false
	}
}

// goFiles lists the non-test .go files of dir: the developer-*.go ones when
// developer is set, every other one otherwise.
func goFiles(t *testing.T, dir string, developer bool) []string {
	t.Helper()

	all, err := filepath.Glob(filepath.Join(dir, "*.go"))
	require.NoError(t, err)

	return slices.DeleteFunc(all, func(path string) bool {
		base := filepath.Base(path)

		return strings.HasSuffix(base, "_test.go") || strings.HasPrefix(base, developerFilePrefix) != developer
	})
}

func parseGo(t *testing.T, path string) *ast.File {
	t.Helper()

	parsed, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	require.NoError(t, err)

	return parsed
}
