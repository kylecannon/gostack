package persist_test

import (
	"bytes"
	"io"
	"os"
	"testing"

	"github.com/kylecannon/gostack/internal/persist"
)

// assetPayloads is the payload axis: small, medium, and a body that crosses the
// 512 KiB spill limit of the ephemeral store.
var assetPayloads = []struct {
	name string
	size int
}{
	{"payload=1KiB", 1 << 10},
	{"payload=64KiB", 64 << 10},
	{"payload=1MiB", 1 << 20},
}

func benchAssets(b *testing.B) (*persist.Assets, string) {
	b.Helper()

	dir := b.TempDir()
	e := benchEngine(dir, flushEvery)
	e.Register(shelfService, newShelf())

	a, err := e.Assets(shelfService)
	if err != nil {
		b.Fatal(err)
	}

	return a, dir
}

// BenchmarkAssetsCommit writes and renames one asset per iteration, which is
// what a persisted PutObject adds to the ephemeral store's cost; the fsync is
// the next save's (BenchmarkSavePendingAssets). The file is unlinked after each
// one, so the disk does not fill.
func BenchmarkAssetsCommit(b *testing.B) {
	for _, payload := range assetPayloads {
		b.Run(payload.name, func(b *testing.B) {
			a, dir := benchAssets(b)
			body := bytes.Repeat([]byte{'x'}, payload.size)

			b.SetBytes(int64(payload.size))

			for b.Loop() {
				w, err := a.Create()
				if err != nil {
					b.Fatal(err)
				}

				_, err = w.Write(body)
				if err != nil {
					b.Fatal(err)
				}

				id, _, err := w.Commit()
				if err != nil {
					b.Fatal(err)
				}

				err = os.Remove(blobFile(dir, id))
				if err != nil {
					b.Fatal(err)
				}
			}
		})
	}
}

// BenchmarkSavePendingAssets, one save of a service with 100, 1000 or 10000
// pending 1 KiB assets, is left out (docs/standards.md, "Benchmarks"). A save
// of pending assets ends in one syncfs on Linux, and that floor is what the
// cell measures, whatever its size: on linux/arm64 (golang:1.27.4 in a
// container, TMPDIR on a loop-mounted ext4 image) one pending asset took 13.2
// to 18.8 ms, 10 took 14.0 to 14.6 and 30 took 14.8 to 15.6, the three runs at
// -benchtime=500ms of each, so shrinking the cell does not bring it under the
// limit. The payload axis of an asset is covered by BenchmarkAssetsCommit, and
// the save of the snapshot alone by BenchmarkSQSFlushFsync.

// BenchmarkAssetsOpen opens one asset and reads it whole per iteration.
func BenchmarkAssetsOpen(b *testing.B) {
	for _, payload := range assetPayloads {
		b.Run(payload.name, func(b *testing.B) {
			a, _ := benchAssets(b)

			w, err := a.Create()
			if err != nil {
				b.Fatal(err)
			}

			_, err = w.Write(bytes.Repeat([]byte{'x'}, payload.size))
			if err != nil {
				b.Fatal(err)
			}

			id, _, err := w.Commit()
			if err != nil {
				b.Fatal(err)
			}

			b.SetBytes(int64(payload.size))

			for b.Loop() {
				f, err := a.Open(id)
				if err != nil {
					b.Fatal(err)
				}

				_, err = io.Copy(io.Discard, f)
				_ = f.Close()

				if err != nil {
					b.Fatal(err)
				}
			}
		})
	}
}
